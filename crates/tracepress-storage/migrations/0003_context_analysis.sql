CREATE TABLE context_snapshots (
    snapshot_id TEXT NOT NULL PRIMARY KEY,
    session_id TEXT NOT NULL REFERENCES sessions(session_id),
    provider_request_id TEXT NOT NULL REFERENCES provider_requests(request_id),
    inference_operation_id TEXT NOT NULL REFERENCES operations(operation_id),
    analysis_version INTEGER NOT NULL CHECK(analysis_version >= 0),
    status TEXT NOT NULL,
    started_at_us INTEGER NOT NULL CHECK(started_at_us >= 0),
    completed_at_us INTEGER CHECK(completed_at_us >= 0),
    recovered_at_us INTEGER CHECK(recovered_at_us >= 0),
    request_content_hash BLOB CHECK(length(request_content_hash) = 32),
    explicit_block_count INTEGER CHECK(explicit_block_count >= 0),
    analyzed_bytes INTEGER CHECK(analyzed_bytes >= 0),
    skipped_bytes INTEGER CHECK(skipped_bytes >= 0),
    explicit_request_complete INTEGER CHECK(explicit_request_complete IN (0, 1)),
    uses_previous_response INTEGER CHECK(uses_previous_response IN (0, 1)),
    uses_conversation_state INTEGER CHECK(uses_conversation_state IN (0, 1)),
    uses_item_references INTEGER CHECK(uses_item_references IN (0, 1)),
    uses_prompt_reference INTEGER CHECK(uses_prompt_reference IN (0, 1)),
    uses_external_files INTEGER CHECK(uses_external_files IN (0, 1)),
    uses_external_images INTEGER CHECK(uses_external_images IN (0, 1)),
    contains_opaque_items INTEGER CHECK(contains_opaque_items IN (0, 1)),
    logical_context_status TEXT,
    duplicate_key_detected INTEGER CHECK(duplicate_key_detected IN (0, 1)),
    reference_resolved_locally INTEGER CHECK(reference_resolved_locally IN (0, 1)),
    correlation_status TEXT,
    UNIQUE(provider_request_id, analysis_version)
) STRICT;

CREATE INDEX context_snapshots_session_idx ON context_snapshots(session_id, snapshot_id);

CREATE TABLE context_block_occurrences (
    block_occurrence_id TEXT NOT NULL PRIMARY KEY,
    snapshot_id TEXT NOT NULL REFERENCES context_snapshots(snapshot_id),
    ordinal INTEGER NOT NULL CHECK(ordinal >= 0),
    parent_block_occurrence_id TEXT REFERENCES context_block_occurrences(block_occurrence_id),
    kind TEXT NOT NULL,
    role TEXT NOT NULL,
    origin TEXT NOT NULL,
    semantic_path TEXT CHECK(length(semantic_path) <= 256),
    semantic_path_truncated INTEGER CHECK(semantic_path_truncated IN (0, 1)),
    semantic_path_hash BLOB CHECK(length(semantic_path_hash) = 32),
    raw_value_start INTEGER NOT NULL CHECK(raw_value_start >= 0),
    raw_value_end INTEGER NOT NULL CHECK(raw_value_end >= raw_value_start),
    locator_occurrence INTEGER NOT NULL CHECK(locator_occurrence >= 0),
    raw_bytes INTEGER NOT NULL CHECK(raw_bytes >= 0),
    exact_fingerprint BLOB CHECK(length(exact_fingerprint) = 32),
    semantic_fingerprint BLOB CHECK(length(semantic_fingerprint) = 32),
    fingerprint_version INTEGER CHECK(fingerprint_version >= 0),
    estimated_tokens INTEGER CHECK(estimated_tokens >= 0),
    estimator TEXT CHECK(length(estimator) <= 64),
    estimator_version INTEGER CHECK(estimator_version >= 0),
    estimator_encoding TEXT CHECK(length(estimator_encoding) <= 64),
    estimate_confidence TEXT,
    detected_kind TEXT,
    detector_confidence REAL CHECK(detector_confidence BETWEEN 0.0 AND 1.0),
    detector_version INTEGER CHECK(detector_version >= 0),
    tool_call_id TEXT CHECK(length(tool_call_id) <= 128),
    tool_name TEXT CHECK(length(tool_name) <= 128),
    tool_name_truncated INTEGER CHECK(tool_name_truncated IN (0, 1)),
    tool_name_hash BLOB CHECK(length(tool_name_hash) = 32),
    line_count INTEGER CHECK(line_count >= 0),
    max_line_length INTEGER CHECK(max_line_length >= 0),
    duplicate_line_ratio REAL CHECK(duplicate_line_ratio BETWEEN 0.0 AND 1.0),
    unique_line_ratio REAL CHECK(unique_line_ratio BETWEEN 0.0 AND 1.0),
    json_item_count INTEGER CHECK(json_item_count >= 0),
    json_depth INTEGER CHECK(json_depth >= 0),
    error_line_density REAL CHECK(error_line_density BETWEEN 0.0 AND 1.0),
    warning_line_density REAL CHECK(warning_line_density BETWEEN 0.0 AND 1.0),
    repetition_score REAL CHECK(repetition_score BETWEEN 0.0 AND 1.0),
    opportunity_signals TEXT CHECK(length(opportunity_signals) <= 256),
    candidate_estimated_tokens INTEGER CHECK(candidate_estimated_tokens >= 0),
    UNIQUE(snapshot_id, ordinal),
    CHECK(parent_block_occurrence_id IS NULL OR parent_block_occurrence_id <> block_occurrence_id)
) STRICT;

CREATE INDEX context_block_occurrences_exact_fingerprint_idx
    ON context_block_occurrences(exact_fingerprint);

CREATE INDEX context_block_occurrences_semantic_fingerprint_idx
    ON context_block_occurrences(semantic_fingerprint);

