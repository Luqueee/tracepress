CREATE TABLE context_deltas (
    current_snapshot_id TEXT NOT NULL PRIMARY KEY REFERENCES context_snapshots(snapshot_id),
    previous_snapshot_id TEXT NOT NULL REFERENCES context_snapshots(snapshot_id),
    repeated_blocks INTEGER CHECK(repeated_blocks >= 0),
    new_blocks INTEGER CHECK(new_blocks >= 0),
    changed_blocks INTEGER CHECK(changed_blocks >= 0),
    removed_blocks INTEGER CHECK(removed_blocks >= 0),
    repeated_estimated_tokens INTEGER CHECK(repeated_estimated_tokens >= 0),
    new_estimated_tokens INTEGER CHECK(new_estimated_tokens >= 0),
    common_prefix_blocks INTEGER CHECK(common_prefix_blocks >= 0),
    common_prefix_estimated_tokens INTEGER CHECK(common_prefix_estimated_tokens >= 0),
    CHECK(previous_snapshot_id <> current_snapshot_id)
) STRICT;

CREATE TABLE token_reconciliations (
    snapshot_id TEXT NOT NULL PRIMARY KEY REFERENCES context_snapshots(snapshot_id),
    attempt_id TEXT REFERENCES provider_usage(attempt_id),
    visible_estimated_tokens INTEGER CHECK(visible_estimated_tokens >= 0),
    provider_input_tokens INTEGER CHECK(provider_input_tokens >= 0),
    residual_tokens INTEGER,
    comparability TEXT NOT NULL
) STRICT;
